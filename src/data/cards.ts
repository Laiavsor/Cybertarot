export type Suit = 'swords' | 'banks' | 'wires' | 'nuyen';
export type Arcana = 'major' | 'minor';

export interface TarotCard {
  id: string;
  arcana: Arcana;
  suit?: Suit;
  rank?: number;          // для младших: 1–10, 11 Page, 12 Knight, 13 Queen, 14 King
  majorNumber?: number;   // для старших: 0–21
  nameEn: string;
  epithet: string;        // киберпанк-эпитет на английском
  nameRu: string;
  suitEn?: string;
  suitRu?: string;
  keywords: string[];     // русские ключи
  upright: string;        // русское толкование (прямая)
  reversed: string;       // русское толкование (перевёрнутая)
  image?: string;         // нейро-арт старших арканов
}


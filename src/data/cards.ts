export const CARD_MAP: Record<string, TarotCard> = Object.fromEntries(CARDS.map((c) => [c.id, c]));

export const SUIT_ORDER: Suit[] = ['swords', 'banks', 'wires', 'nuyen'];

export function drawRandom(count: number, exclude: string[] = []): TarotCard[] {
  const pool = CARDS.filter((c) => !exclude.includes(c.id));
  const copy = [...pool];
  const out: TarotCard[] = [];
  while (out.length < count && copy.length) {
    const i = Math.floor(Math.random() * copy.length);
    out.push(copy.splice(i, 1)[0]);
  }
  return out;
}
